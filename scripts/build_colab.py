def collect_results(kaggle: bool) -> str:
    """Last cell: zip what the submission needs (plots, eval files, small adapter JSON; no weights)."""
    deliver = (
        "print('Saved next to the notebook output: lab22_results.zip')"
        if kaggle
        else "from google.colab import files\nfiles.download(str(out))"
    )
    return (
        "# Run this cell any time (also after a failed stage) to collect what has been produced so far.\n"
        "import zipfile\n"
        "from pathlib import Path\n\n"
        "root = Path.cwd()\n"
        "out = root.parent / 'lab22_results.zip'\n"
        "skip = ('tokenizer', 'vocab', 'added_tokens', 'special_tokens_map', 'chat_template')\n"
        "picked = [p for d in ('submission/screenshots', 'data/eval', 'data/pref') for p in (root / d).rglob('*')]\n"
        "picked += [p for p in (root / 'adapters').rglob('*.json')\n"
        "           if 'checkpoint' not in p.as_posix() and not p.name.startswith(skip)]\n"
        "picked = sorted(p for p in picked if p.is_file() and p.name != '.gitkeep')\n"
        "with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as z:\n"
        "    for p in picked:\n"
        "        z.write(p, p.relative_to(root))\n"
        "print(f'{len(picked)} files, {out.stat().st_size / 1e6:.1f} MB -> {out}')\n"
        "for name in ('02-sft-loss.png', '02b-pref-length.png', '03-dpo-reward-curves.png', '04-side-by-side-table.png'):\n"
        "    if not (root / 'submission/screenshots' / name).exists():\n"
        "        print(f'MISSING core screenshot: {name}')\n"
        "for rel in ('adapters/dpo/dpo_metrics.json', 'data/eval/side_by_side.jsonl', 'data/eval/judge_summary.json'):\n"
        "    if not (root / rel).exists():\n"
        "        print(f'MISSING core result: {rel}')\n"
        + deliver
    )


def render(tier: str, kaggle: bool = False) -> dict:
    big = tier == "BIGGPU"
    workdir = KAGGLE_WORKDIR if kaggle else WORKDIR
    pins = " ".join(f'"{s}"' for s in requirements())
    cells = [
        md(
            KAGGLE_HEADER
            if kaggle
            else f"# Lab 22 — DPO/ORPO Alignment ({'BigGPU' if big else 'T4'} tier)\n\n"
            "**Track 3 · Day 22 · VinUni AICB.** Generated by `scripts/build_colab.py` from "
            "`notebooks/*.py` and `lab22/*.py`; do not edit by hand.\n\n"
            "Core: NB0 → NB4. Bonus: NB3b (variants), NB5 (GGUF), NB6 (lm-eval), NB7 (GRPO).\n"
            "Each stage reloads what it needs from disk, so after a crash you can restart the "
            "runtime, rerun section A, and continue from the stage that failed."
        ),
        md("## A. Setup"),
        code(
            KAGGLE_SETUP
            if kaggle
            else "import os\n"
            f'os.environ["COMPUTE_TIER"] = "{tier}"\n'
            "# NB4 judges automatically with a panel of two local reward models (no key needed).\n"
            "# Optional API judge as a cross-check (two A/B orders):\n"
            '# os.environ["JUDGE_PROVIDER"] = "gemini"   # or "openai" / "anthropic"\n'
            '# os.environ["JUDGE_MODEL"] = "<current model id>"\n'
            '# from google.colab import userdata; os.environ["GEMINI_API_KEY"] = userdata.get("GEMINI_API_KEY")\n'
            "# Put API keys in Colab secrets, never in the notebook."
        ),
        code(f"!pip install -q {pins}" + (' "vllm>=0.10"' if big else "")),
        code(
            "from pathlib import Path\n"
            f'WORK = Path("{workdir}")\n'
            '(WORK / "lab22").mkdir(parents=True, exist_ok=True)\n'
            "os.chdir(WORK)\n"
            "print(Path.cwd())"
        ),
        md("### Helper package `lab22/` (same files as the repo)"),
    ]
    for module in sorted((REPO / "lab22").glob("*.py")):
        body = module.read_text(encoding="utf-8")
        cells.append(code(f"%%writefile {workdir}/lab22/{module.name}\n{body}"))
    for i, (stem, kind) in enumerate(STAGES):
        if i:
            # One Colab kernel runs every stage, so drop the previous stage's GPU objects.
            cells.append(code(RELEASE_GPU))
        cells.append(md(f"---\n# ⏵ `notebooks/{stem}.py` ({kind})"))
        cells.extend(percent_cells(REPO / "notebooks" / f"{stem}.py"))
    cells.append(md("---\n# ⏵ Collect results\n\nUnzip into the repo root, then commit. Model weights are left out."))
    cells.append(code(collect_results(kaggle)))
    metadata = {
        "kernelspec": {"display_name": "Python 3", "name": "python3"},
        "language_info": {"name": "python"},
    }
    if kaggle:
        metadata["kaggle"] = {
            "accelerator": "nvidiaTeslaT4",
            "dataSources": [],
            "isGpuEnabled": True,
            "isInternetEnabled": True,
            "language": "python",
            "sourceType": "notebook",
        }
    else:
        metadata["accelerator"] = "GPU"
        metadata["colab"] = {"gpuType": "A100" if big else "T4", "provenance": []}
    return {
        "cells": cells,
        "metadata": metadata,
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if colab/*.ipynb differ from the sources")
    args = parser.parse_args()
    stale = []
    jobs = [(REPO / "colab" / name, render(tier)) for tier, name in TARGETS.items()]
    jobs.append((REPO / "kaggle" / KAGGLE_TARGET, render("T4", kaggle=True)))
    for path, nb in jobs:
        name = path.relative_to(REPO).as_posix()
        if args.check:
            if not path.exists() or json.loads(path.read_text(encoding="utf-8")) != nb:
                stale.append(name)
            continue
        path.parent.mkdir(exist_ok=True)
        path.write_text(json.dumps(nb, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"wrote {name} ({len(nb['cells'])} cells)")
    if stale:
        print(f"stale: {stale}; run `python scripts/build_colab.py`")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
